def hours_words(clinic, at, lang: str) -> dict:
    """Format values shared by the opening-hours messages."""
    from .queue_service import next_open_day  # local import avoids a cycle

    d = next_open_day(clinic, at)
    P = PAGE[lang]
    day = P["today"] if d == at.date() else P["weekdays"][d.weekday()]
    return {
        "day": day,
        "opens": clock_text(clinic.opens),
        "closes": clock_text(clinic.closes),
        "line_opens": clock_text(clinic.line_opens),
        "last_join": clock_text(clinic.last_join),
    }


def clock_text(t) -> str:
    """8:05 AM style, no leading zero."""
    h = t.hour % 12 or 12
    return f"{h}:{t.minute:02d} {'AM' if t.hour < 12 else 'PM'}"
